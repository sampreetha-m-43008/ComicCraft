"""
Step 5: export the comic as a PDF.

CHANGE FROM THE SPEC: the old `fpdf` package is unmaintained. Its maintained successor
`fpdf2` keeps the same `from fpdf import FPDF` import, so the code looks the same.
"""
import logging
from datetime import datetime

from fpdf import FPDF

from . import config
from .errors import ExportError

logger = logging.getLogger("comiccraft.export")

_REPLACEMENTS = {"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
                 "\u2013": "-", "\u2014": "-", "\u2026": "...", "\u00a0": " "}


def _safe(text: str) -> str:
    """Built-in PDF fonts only support Latin-1, so replace fancy characters."""
    for old, new in _REPLACEMENTS.items():
        text = text.replace(old, new)
    return text.encode("latin-1", "replace").decode("latin-1")


def _write_block(pdf: FPDF, label: str, text: str) -> None:
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 6, _safe(label), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.multi_cell(0, 6, _safe(text), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)


def save_pdf(layout: list, comic_title: str, demo: bool = False) -> str:
    """Build the PDF and return its path relative to the project root."""
    try:
        config.EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
        pdf = FPDF(format="A4")
        pdf.set_auto_page_break(auto=True, margin=15)

        # Title page
        pdf.add_page()
        pdf.set_font("Helvetica", "B", 26)
        pdf.ln(60)
        pdf.multi_cell(0, 14, _safe(comic_title), align="C", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 12)
        pdf.ln(6)
        pdf.cell(0, 8, "Created with ComicCraft", align="C", new_x="LMARGIN", new_y="NEXT")
        if demo:
            pdf.set_text_color(180, 0, 0)
            pdf.multi_cell(0, 8, "DEMO MODE - placeholder content, not generated by AI",
                           align="C", new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(0, 0, 0)

        # One page per panel
        for panel in layout:
            pdf.add_page()
            pdf.set_font("Helvetica", "B", 16)
            pdf.multi_cell(0, 9, _safe(f"Panel {panel['panel_number']}: {panel['title']}"),
                           new_x="LMARGIN", new_y="NEXT")
            pdf.ln(2)
            image_file = config.BASE_DIR / panel["image"].lstrip("/")  # pathlib = Windows-safe
            if not image_file.exists():
                raise FileNotFoundError(f"Image not found: {image_file}")
            pdf.image(str(image_file), x=20, w=170)
            pdf.ln(4)
            _write_block(pdf, "Caption", panel["caption"])
            _write_block(pdf, "Scene", panel["scene_description"])
            _write_block(pdf, "Narration", panel["narration"])
            _write_block(pdf, "Dialogue", panel["dialogue"])

        filename = f"comic_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
        out_path = config.EXPORTS_DIR / filename
        pdf.output(str(out_path))
        return out_path.relative_to(config.BASE_DIR).as_posix()
    except Exception as exc:
        logger.exception("PDF export failed")
        raise ExportError(str(exc)) from exc
